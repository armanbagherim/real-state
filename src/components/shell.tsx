function GlobalSearch() {
  const [query, setQuery] = useState("");
  const [results, setResults] = useState<
    {
      id: string;
      title: string;
      fileCode: string;
      owner: { fullName: string };
    }[]
  >([]);
  const [active, setActive] = useState(false);
  const [busy, setBusy] = useState(false);
  const [failed, setFailed] = useState(false);
  const input = useRef<HTMLInputElement>(null);
  const router = useRouter();
  useEffect(() => {
    const h = (e: KeyboardEvent) => {
      if ((e.ctrlKey || e.metaKey) && e.key === "k") {
        e.preventDefault();
        input.current?.focus();
      }
    };
    window.addEventListener("keydown", h);
    return () => window.removeEventListener("keydown", h);
  }, []);
  useEffect(() => {
    if (query.trim().length < 2) return;
    const controller = new AbortController();
    const timer = setTimeout(async () => {
      setBusy(true);
      setFailed(false);
      try {
        const response = await fetch(
          `/api/search?q=${encodeURIComponent(query)}`,
          { signal: controller.signal },
        );
        if (!response.ok) throw new Error();
        setResults(await response.json());
      } catch (e) {
        if ((e as Error).name !== "AbortError") setFailed(true);
      } finally {
        setBusy(false);
      }
    }, 300);
    return () => {
      clearTimeout(timer);
      controller.abort();
    };
  }, [query]);
  return (
    <div className="global-search">
      <Search size={18} />
      <input
        aria-label="جستجوی سراسری"
        ref={input}
        className=""
        placeholder="جستجوی فایل، مالک، شماره تماس…"
        value={query}
        onFocus={() => setActive(true)}
        onBlur={() => setTimeout(() => setActive(false), 180)}
        onChange={(e) => {
          setQuery(e.target.value);
          setResults([]);
        }}
        onKeyDown={(e) => {
          if (e.key === "Escape") setActive(false);
          if (e.key === "Enter") {
            setActive(false);
            router.push(`/properties?q=${encodeURIComponent(query)}`);
          }
        }}
      />
      <kbd>
        <Command size={11} /> K
      </kbd>
      {active && query.length >= 2 && (
        <div className="search-results">
          {busy ? (
            <p>در حال جستجو…</p>
          ) : failed ? (
            <p>جستجو انجام نشد؛ دوباره تلاش کنید.</p>
          ) : results.length ? (
            results.map((r) => (
              <Link
                key={r.id}
                href={`/properties/${r.id}`}
                onClick={() => setActive(false)}
              >
                <span>
                  <b>{r.title}</b>
                  <small>{r.owner.fullName}</small>
                </span>
                <span dir="ltr">{r.fileCode}</span>
              </Link>
            ))
          ) : (
            <p>نتیجه‌ای پیدا نشد.</p>
          )}
        </div>
      )}
    </div>
  );
}
